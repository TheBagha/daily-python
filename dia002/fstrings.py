# Format e F-strings

nome = input("Digite seu nome: ")
idade = int(input("Digite sua idade: "))

print(f"Meu nome é {nome} e tenho {idade} anos de idade.") # Forma mais rapida e simples de se formatar textos em python
print("Meu nome é {} e tenho {} anos de idade.".format(nome, idade)) # Forma mais complexa de se formatar textos em python porém resulta no mesmo