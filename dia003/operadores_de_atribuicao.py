# Operadores de atribuição

# Operadores de atribuição servem pra atualizar o valor de uma variável sem precisar reescrever ela inteira

x = 10

x += 2   # x = x + 2  -> 12
print(x)
x -= 2   # x = x - 2  -> 8
print(x)
x *= 2   # x = x * 2  -> 20
print(x)
x /= 2   # x = x / 2  -> 5.0
print(x)
x //= 2  # x = x // 2
print(x)
x %= 2   # x = x % 2
print(x)
x **= 2  # x = x ** 2
print(x)