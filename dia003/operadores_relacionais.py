# Operadores relacionais

# Devolvem True ou False
a = 10
b = 5

print("a =", a)
print("b =", b)

print("a > b:", a > b)     # maior que
print("a < b:", a < b)     # menor que
print("a >= b:", a >= b)   # maior ou igual
print("a <= b:", a <= b)   # menor ou igual
print("a == b:", a == b)   # igual
print("a != b:", a != b)   # diferente